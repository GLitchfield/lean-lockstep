from __future__ import annotations

import json
import time
from datetime import date, datetime, timedelta

from lockstep import EXIT_OK
from lockstep.context import Ctx
from lockstep.gitutil import git
from lockstep.output import Result
from lockstep.spec import Arg, CommandSpec, command
from lockstep.store import Store


def run(ctx: Ctx, since: str | None = None, write: bool = True) -> Result:
    cfg = ctx.cfg
    if since:
        start = datetime.strptime(since, "%Y-%m-%d")
    else:
        today = date.today()
        start = datetime.combine(today - timedelta(days=today.weekday() + 7), datetime.min.time())
    end = start + timedelta(days=7)
    iso = start.isocalendar()
    week = f"{iso[0]}-W{iso[1]:02d}"
    with Store(cfg) as st:
        events = [dict(e) for e in st.events_since(start.timestamp()) if e["at"] < end.timestamp()]
        attempts = [dict(a) for a in st.attempts(since=start.timestamp()) if (a["started_at"] or 0) < end.timestamp()]
        jobs = [j for j in st.jobs(limit=1000) if start.timestamp() <= j["created_at"] < end.timestamp()]
    by_kind: dict[str, list[dict]] = {}
    for e in events:
        by_kind.setdefault(e["kind"], []).append(e)
    job_seconds = sum((j.get("finished_at") or 0) - (j.get("started_at") or 0) for j in jobs if j.get("started_at") and j.get("finished_at"))
    # committed-file changes in the window
    def log_for(path: str) -> list[str]:
        try:
            out = git(cfg, "log", f"--since={start:%Y-%m-%d}", f"--until={end:%Y-%m-%d}", "--format=%h %as %s", "--", path, check=False)
        except (RuntimeError, OSError):
            return []
        return [line for line in out.splitlines() if line.strip()]
    lock_changes = log_for(str(cfg.lock_file.relative_to(cfg.root)))
    allow_changes = log_for(str(cfg.allowlist_file.relative_to(cfg.root)))
    status_changes = log_for(str(cfg.status_md.relative_to(cfg.root)))
    outcomes: dict[str, int] = {}
    for a in attempts:
        outcomes[a.get("outcome") or "live"] = outcomes.get(a.get("outcome") or "live", 0) + 1
    lines = [f"# Week {week} ({start:%Y-%m-%d} to {end - timedelta(days=1):%Y-%m-%d})", "",
             "Generated by `lockstep note`; the Judgment section is written by a human.", "", "## Nodes", ""]
    for kind, label in (("node-added", "opened"), ("closed", "closed"), ("refuted", "refuted"), ("retired", "retired"), ("node-restated", "restated")):
        names = sorted({e["node"] for e in by_kind.get(kind, []) if e.get("node")})
        lines.append(f"- {label}: {len(names)}" + (" (" + ", ".join(f"`{n}`" for n in names) + ")" if names else ""))
    lines += ["", "## Attempts", "", f"- attempts started this week: {len(attempts)}"]
    lines += [f"- outcome {k}: {v}" for k, v in sorted(outcomes.items())]
    lines += ["", "## Evidence", ""]
    fals = by_kind.get("falsify", [])
    lines.append(f"- falsifier runs: {len(fals)}" + (" (" + ", ".join(f"`{e['node']}`: {json.loads(e['detail'] or '{}').get('result')}" for e in fals) + ")" if fals else ""))
    lines.append(f"- allowlist changes: {len(allow_changes)}" + (" — " + "; ".join(allow_changes) if allow_changes else ""))
    lines.append(f"- statement lock changes: {len(lock_changes)}" + (" — " + "; ".join(lock_changes) if lock_changes else ""))
    lines.append(f"- status.md commits: {len(status_changes)}")
    lines += ["", "## Compute", "", f"- jobs: {len(jobs)} ({job_seconds / 3600:.1f} h of job time)", "", "## Judgment", "", "", ""]
    text = "\n".join(lines)
    out = cfg.notes_dir / f"{week}.md"
    if write:
        out.parent.mkdir(parents=True, exist_ok=True)
        if out.exists() and "## Judgment" in out.read_text():
            old = out.read_text()
            judgment = old.split("## Judgment", 1)[1]
            text = text.split("## Judgment", 1)[0] + "## Judgment" + judgment
        out.write_text(text)
    res = Result(EXIT_OK, {"week": week, "path": str(out.relative_to(cfg.root)), "events": len(events), "attempts": len(attempts)}, text.splitlines())
    if write:
        res.line(f"wrote {out.relative_to(cfg.root)}")
    return res


command(CommandSpec(name="note", cli=["note"], help="Weekly note from status diffs and the attempts table; leaves `## Judgment` for the human.", run=run,
                    args=[Arg("since", "week start date YYYY-MM-DD (default: last week)"), Arg("write", "write docs/notes/<ISO-week>.md", "bool", default=True)]))
