def _other_checkout(cfg, tmp_path: Path) -> Path:
    other = tmp_path / "other"
    (other / "harness").mkdir(parents=True)
    shutil.copy2(cfg.root / "harness/config.toml", other / "harness/config.toml")
    (other / "TCore").mkdir()
    (other / "TCore.lean").write_text("import TCore.Chunk000\n")
    (other / "TCore/Chunk000.lean").write_text("-- generated by test\n")
    (other / "TBlueprint").mkdir()
    (other / "TBlueprint.lean").write_text("")
    (other / "lean-toolchain").write_text("leanprover/lean4:v4.29.1\n")
    (cfg.root / "lean-toolchain").write_text("leanprover/lean4:v4.29.1\n")
    return other


def _artifact(root: Path, contents: bytes = b"proof body") -> Path:
    path = root / ".lake/build/lib/lean/TCore/Chunk000.olean.private"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(contents)
    return path


def _receipt(tmp_path: Path) -> Receipt:
    return Receipt(tmp_path / "receipt.jsonl", {
        "schema": "test", "event": "start", "primary": "a", "other": "b", "cache": "c",
        "toolchain": "t", "facets": ["olean.private"],
    })


def test_discovers_only_matching_certificate_compiled_facets(cfg, tmp_path):
    other = _other_checkout(cfg, tmp_path)
    primary_artifact = _artifact(cfg.root)
    other_artifact = _artifact(other)
    # Mutable sidecars exist but are outside the facet allowlist and discovery.
    Path(str(primary_artifact) + ".hash").write_text("mutable")
    (primary_artifact.parent / "Chunk000.setup.json").write_text("{}")
    other_cfg = validate_roots(cfg, other)

    found, stats = certificate_candidates(cfg, other_cfg, ["olean.private"])

    assert [(item.module, item.facet) for item in found] == [("TCore.Chunk000", "olean.private")]
    assert stats["candidate_bytes"] == len(b"proof body")
    assert all(not item.relative_output.endswith((".hash", ".setup.json", ".trace")) for item in found)


def test_rejects_symlinked_output(cfg, tmp_path):
    other = _other_checkout(cfg, tmp_path)
    _artifact(cfg.root)
    target = _artifact(other)
    backing = target.with_name("backing")
    target.replace(backing)
    target.symlink_to(backing.name)

    with pytest.raises(CheckFailed, match="symlink"):
        certificate_candidates(cfg, validate_roots(cfg, other), ["olean.private"])


def test_rejects_symlinked_output_ancestor(cfg, tmp_path):
    other = _other_checkout(cfg, tmp_path)
    _artifact(cfg.root)
