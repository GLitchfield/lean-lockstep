def test_sha256_mismatch_is_receipted_and_not_verified(tmp_path):
    primary = tmp_path / "a"
    other = tmp_path / "b"
    primary.write_bytes(b"aaaa")
    other.write_bytes(b"bbbb")
    item = Candidate("TCore.Chunk", "olean.private", "x", primary, other, 4)
    receipt = _receipt(tmp_path)

    assert verify_candidates([item], receipt) == []
    assert '"event":"mismatch"' in receipt.path.read_text()


def test_verification_detects_source_inode_replacement(tmp_path, monkeypatch):
    from lockstep import artifact_cache

    primary = tmp_path / "a"
    other = tmp_path / "b"
    primary.write_bytes(b"same")
    other.write_bytes(b"same")
    item = Candidate("TCore.Chunk", "olean.private", "x", primary, other, 4)
    real_hash = artifact_cache.sha256_file

    def replacing_hash(path):
        digest = real_hash(path)
        if path == primary:
            replacement = tmp_path / "replacement"
            replacement.write_bytes(b"same")
            os.replace(replacement, primary)
        return digest

    monkeypatch.setattr(artifact_cache, "sha256_file", replacing_hash)
    with pytest.raises(CheckFailed, match="changed while hashing"):
        verify_candidates([item], _receipt(tmp_path))


def test_atomic_adoption_links_exact_blob_and_rejects_collision(tmp_path):
    path = tmp_path / "local.olean.private"
    blob = tmp_path / "cache.olean.private"
    path.write_bytes(b"same proof")
    blob.write_bytes(b"same proof")
    digest = sha256_file(path)

    before, after = atomic_adopt(path, blob, digest)

    assert before.inode != after.inode
    assert _identity(path).inode == _identity(blob).inode
    collision = tmp_path / "collision.olean.private"
    collision.write_bytes(b"evil proof")
    with pytest.raises(CheckFailed, match="collision|corrupt"):
        atomic_adopt(path, collision, digest)


def test_atomic_adoption_detects_mutation_before_replace(tmp_path, monkeypatch):
    path = tmp_path / "local.olean.private"
    blob = tmp_path / "cache.olean.private"
    path.write_bytes(b"same proof")
    blob.write_bytes(b"same proof")
    digest = sha256_file(path)
    real_link = os.link

    def racing_link(source, destination, **kwargs):
        real_link(source, destination, **kwargs)
        path.write_bytes(b"raced proof")

    monkeypatch.setattr(os, "link", racing_link)
    with pytest.raises(CheckFailed, match="changed during adoption"):
        atomic_adopt(path, blob, digest)
    assert not list(tmp_path.glob(".*.lockstep-share-*"))


def test_atomic_adoption_detects_blob_mutation(tmp_path, monkeypatch):
    path = tmp_path / "local.olean.private"
    blob = tmp_path / "cache.olean.private"
    path.write_bytes(b"same proof")
    blob.write_bytes(b"same proof")
    digest = sha256_file(path)
    original_inode = _identity(path).inode
    real_link = os.link

    def mutating_link(source, destination, **kwargs):
        real_link(source, destination, **kwargs)
        blob.chmod(0o644)
        blob.write_bytes(b"evil proof")

    monkeypatch.setattr(os, "link", mutating_link)
    with pytest.raises(CheckFailed, match="blob changed"):
        atomic_adopt(path, blob, digest)
    assert _identity(path).inode == original_inode
    assert not list(tmp_path.glob(".*.lockstep-share-*"))


def test_atomic_adoption_rename_failure_preserves_original(tmp_path, monkeypatch):
    path = tmp_path / "local.olean.private"
    blob = tmp_path / "cache.olean.private"
    path.write_bytes(b"same proof")
    blob.write_bytes(b"same proof")
    digest = sha256_file(path)
    original = _identity(path)

    def failed_replace(*_args, **_kwargs):
        raise OSError("injected rename failure")

    monkeypatch.setattr(os, "replace", failed_replace)
    with pytest.raises(CheckFailed, match="atomic adoption failed"):
        atomic_adopt(path, blob, digest)
    assert _identity(path).inode == original.inode
    assert path.read_bytes() == b"same proof"
    assert not list(tmp_path.glob(".*.lockstep-share-*"))


def test_receipt_repairs_torn_tail_before_resuming(tmp_path):
    receipt = _receipt(tmp_path)
    with receipt.path.open("ab") as stream:
        stream.write(b'{"event":"adopted"')
    resumed = _receipt(tmp_path)
    resumed.append({"event": "adopted", "module": "M", "facet": "olean.private"})

    rows = [__import__("json").loads(line) for line in resumed.path.read_text().splitlines()]
    assert [row["event"] for row in rows] == ["start", "adopted"]
    assert resumed.adopted() == {("M", "olean.private")}


